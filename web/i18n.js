// 画面の言語(日本語 / English)。ほかのスクリプトより先に読む。
// 文字列は日本語の原文をそのまま鍵にして、英語の辞書 I18N_EN で引く(無ければ日本語のまま出し、console.debug で 1 回だけ知らせる)。
// 切り替えは localStorage(yuzu.lang)に覚えて、ページを読み直す。
const LANG_KEY = "yuzu.lang";
const LANG = (() => {
  try { const v = localStorage.getItem(LANG_KEY); if (v === "ja" || v === "en") return v; } catch (e) { /* 使えないときは、ブラウザの言語で決める */ }
  const nav = (typeof navigator !== "undefined" && navigator.language) || "ja";
  return String(nav).toLowerCase().startsWith("ja") ? "ja" : "en";
})();

const I18N_MISSING = new Set();      // 辞書に無かった文字列(知らせるのは 1 回だけ)

// t("シーン {n} / {total}", {n, total}): いまの言語の文字列にして、{名前} を値で埋める
function t(ja, vars) {
  let s = ja;
  if (LANG !== "ja") {
    const en = I18N_EN[ja];
    if (en !== undefined) s = en;
    else if (!I18N_MISSING.has(ja)) { I18N_MISSING.add(ja); try { console.debug("[i18n] 訳がありません:", ja); } catch (e) { /* 何もしない */ } }
  }
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

// data-i18n(文字)・data-i18n-title・data-i18n-placeholder・data-i18n-aria(aria-label)の付いた要素を訳す。
// 値が空の data-i18n は、いまの中身(日本語の原文)を鍵にする。原文は dataset に残すので、何度呼んでもよい。
const I18N_ATTRS = [["i18n", null], ["i18nTitle", "title"], ["i18nPlaceholder", "placeholder"], ["i18nAria", "aria-label"]];
function applyI18n(root) {
  root = root || document;
  if (typeof document !== "undefined" && root === document && document.documentElement) document.documentElement.lang = LANG;
  for (const [key, attr] of I18N_ATTRS) {
    const sel = "[data-" + key.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase()) + "]";
    root.querySelectorAll(sel).forEach((e) => {
      const ja = e.dataset[key] || (attr ? e.getAttribute(attr) : e.textContent.trim()) || "";
      if (!ja) return;
      e.dataset[key] = ja;
      if (attr) e.setAttribute(attr, t(ja));
      else e.textContent = t(ja);
    });
  }
}

function setLang(lang) {
  try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* 覚えられなくても、今回は切り替える */ }
  if (lang !== LANG) location.reload();
}

